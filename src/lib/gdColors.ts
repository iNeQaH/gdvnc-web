export function getGdColor(id: number | null | undefined): [number, number, number] {
  if (id === null || id === undefined || isNaN(id)) return [255, 255, 255];
  const c = GD_COLORS[id];
  return c || [255, 255, 255];
}

export function getGdColorHex(id: number | null | undefined): string {
  const [r, g, b] = getGdColor(id);
  return `#${r.toString(16).padStart(2, '0')}${g.toString(16).padStart(2, '0')}${b.toString(16).padStart(2, '0')}`;
}
